function translateText(value: string): string {
  let translated = value;
  for (const [source, target] of translations) {
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    translated = translated.replace(new RegExp(`(?<!\\p{L})${escaped}(?!\\p{L})`, "giu"), target);
  }
  return translated
    .replace(/\btracts spinal\b/giu, "spinal tracts")
    .replace(/\bnerve suprascapular\b/giu, "suprascapular nerve")
    .replace(/\bnerve ([a-z]+)\b/giu, "$1 nerve");
}

export function localizeNervousText(id: string, value: string, field: NervousField): LocalizedText {
  const en = field === "name"
    ? curatedNames[id] ?? translateText(value)
    : field === "relationship"
      ? translateText(value)
      : curatedFields[id]?.[field] ?? translateText(value);
  return { es: value, en };
}
